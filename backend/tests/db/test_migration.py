"""The real migration builds the schema the models describe, and can be undone."""

from __future__ import annotations

import asyncio

import sqlalchemy as sa
from alembic import command
from sqlalchemy.ext.asyncio import AsyncConnection, create_async_engine
from sqlalchemy.pool import NullPool

from tests.db.conftest import alembic_config

D1_TABLES = {
    "users",
    "cases",
    "documents",
    "pages",
    "lines",
    "extraction_runs",
    "fields",
    "jobs",
    "audit_events",
}
SEQUENCES = {"case_ref_lp_seq", "case_ref_lm_seq"}


async def test_only_the_d1_tables_exist(conn: AsyncConnection) -> None:
    # Later tables (flags, config_versions, analysis_runs ...) arrive in their own migrations.
    result = await conn.execute(
        sa.text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
    )
    assert {row[0] for row in result} == D1_TABLES | {"alembic_version"}


async def test_extensions_installed(conn: AsyncConnection) -> None:
    result = await conn.execute(sa.text("SELECT extname FROM pg_extension"))
    assert {"vector", "pg_trgm"} <= {row[0] for row in result}


async def test_every_row_has_a_uuid_key_and_a_timestamp(conn: AsyncConnection) -> None:
    """The schema doc's conventions: UUID primary keys, created_at (timestamptz) on every row."""
    rows = await conn.execute(
        sa.text(
            "SELECT table_name, column_name, data_type, column_default, is_nullable "
            "FROM information_schema.columns WHERE table_schema = 'public'"
        )
    )
    columns = {(r.table_name, r.column_name): r for r in rows}
    for table in D1_TABLES - {"audit_events"}:
        key = columns[(table, "id")]
        assert key.data_type == "uuid", table
        assert key.column_default == "gen_random_uuid()", table
        created = columns[(table, "created_at")]
        assert (created.data_type, created.is_nullable) == ("timestamp with time zone", "NO"), table
    # audit_events keeps a bigint identity key (orders events within one transaction) and `at`.
    assert columns[("audit_events", "id")].data_type == "bigint"
    at = columns[("audit_events", "at")]
    assert (at.data_type, at.is_nullable) == ("timestamp with time zone", "NO")


async def test_the_case_ref_sequences_exist(conn: AsyncConnection) -> None:
    rows = await conn.execute(sa.text("SELECT sequencename FROM pg_sequences"))
    assert {row[0] for row in rows} >= SEQUENCES


def test_models_match_migration(migrated_db_url: str) -> None:
    # Raises AutogenerateDiffsDetected if the models and the migration disagree.
    command.check(alembic_config(migrated_db_url))


async def _objects(url: str) -> tuple[set[str], set[str], set[str]]:
    engine = create_async_engine(url, poolclass=NullPool)
    try:
        async with engine.connect() as connection:
            tables = await connection.execute(
                sa.text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
            )
            functions = await connection.execute(
                sa.text("SELECT proname FROM pg_proc WHERE proname = 'audit_events_block_mutation'")
            )
            sequences = await connection.execute(sa.text("SELECT sequencename FROM pg_sequences"))
            return {r[0] for r in tables}, {r[0] for r in functions}, {r[0] for r in sequences}
    finally:
        await engine.dispose()


def test_downgrade_removes_everything_and_upgrade_repeats(fresh_db_url: str) -> None:
    config = alembic_config(fresh_db_url)
    command.upgrade(config, "head")
    command.downgrade(config, "base")

    tables, functions, sequences = asyncio.run(_objects(fresh_db_url))
    assert tables == {"alembic_version"}
    assert functions == set()
    assert not SEQUENCES & sequences

    command.upgrade(config, "head")
    tables, functions, sequences = asyncio.run(_objects(fresh_db_url))
    assert tables >= D1_TABLES
    assert functions == {"audit_events_block_mutation"}
    assert sequences >= SEQUENCES
