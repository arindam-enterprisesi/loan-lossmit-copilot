"""The real migration builds the schema the models describe, and can be undone."""

from __future__ import annotations

import asyncio

import sqlalchemy as sa
from alembic import command
from sqlalchemy.ext.asyncio import AsyncConnection, create_async_engine
from sqlalchemy.pool import NullPool

from tests.db.conftest import alembic_config

EXPECTED_TABLES = {
    "users",
    "cases",
    "documents",
    "pages",
    "lines",
    "extraction_runs",
    "fields",
    "jobs",
    "audit_events",
}


async def test_expected_tables_exist(conn: AsyncConnection) -> None:
    result = await conn.execute(
        sa.text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
    )
    assert {row[0] for row in result} >= EXPECTED_TABLES


async def test_extensions_installed(conn: AsyncConnection) -> None:
    result = await conn.execute(sa.text("SELECT extname FROM pg_extension"))
    assert {"vector", "pg_trgm"} <= {row[0] for row in result}


def test_models_match_migration(migrated_db_url: str) -> None:
    # Raises AutogenerateDiffsDetected if the models and the migration disagree.
    command.check(alembic_config(migrated_db_url))


async def _tables_and_functions(url: str) -> tuple[set[str], set[str]]:
    engine = create_async_engine(url, poolclass=NullPool)
    try:
        async with engine.connect() as connection:
            tables = await connection.execute(
                sa.text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
            )
            functions = await connection.execute(
                sa.text("SELECT proname FROM pg_proc WHERE proname = 'audit_events_block_mutation'")
            )
            return {r[0] for r in tables}, {r[0] for r in functions}
    finally:
        await engine.dispose()


def test_downgrade_removes_everything_and_upgrade_repeats(fresh_db_url: str) -> None:
    config = alembic_config(fresh_db_url)
    command.upgrade(config, "head")
    command.downgrade(config, "base")

    tables, functions = asyncio.run(_tables_and_functions(fresh_db_url))
    assert tables == {"alembic_version"}
    assert functions == set()

    command.upgrade(config, "head")
    tables, functions = asyncio.run(_tables_and_functions(fresh_db_url))
    assert tables >= EXPECTED_TABLES
    assert functions == {"audit_events_block_mutation"}
